package com.pictorial.artwork_service.document;

public class GoldsmithDocument {

    private String material;
    private String preciousStones;
    private Double weight;

    public GoldsmithDocument() {}

    public String getMaterial() { return material; }
    public void setMaterial(String material) { this.material = material; }
    public String getPreciousStones() { return preciousStones; }
    public void setPreciousStones(String preciousStones) { this.preciousStones = preciousStones; }
    public Double getWeight() { return weight; }
    public void setWeight(Double weight) { this.weight = weight; }
}
